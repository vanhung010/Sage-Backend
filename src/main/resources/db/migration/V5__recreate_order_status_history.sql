CREATE TABLE sage.order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    from_status VARCHAR(20) NOT NULL,
    to_status VARCHAR(20) NOT NULL,
    changed_by BIGINT,
    reason TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_status_history_order_id
        FOREIGN KEY (order_id) REFERENCES sage.orders (id),
    CONSTRAINT fk_order_status_history_changed_by
        FOREIGN KEY (changed_by) REFERENCES sage.users (id),
    CONSTRAINT ck_order_history_from_status
        CHECK (from_status IN ('PENDING', 'ACCEPTED', 'DENIED', 'DELIVERING', 'SUCCESSFUL', 'PREPARING', 'REFUND')),
    CONSTRAINT ck_order_history_to_status
        CHECK (to_status IN ('PENDING', 'ACCEPTED', 'DENIED', 'DELIVERING', 'SUCCESSFUL', 'PREPARING', 'REFUND')),
    CONSTRAINT ck_order_history_changed
        CHECK (from_status <> to_status),
    CONSTRAINT ck_order_history_reason
        CHECK (to_status <> 'DENIED' OR (reason IS NOT NULL AND btrim(reason) <> ''))
);
